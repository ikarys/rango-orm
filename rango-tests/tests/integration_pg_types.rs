/// Integration tests for column types on PostgreSQL: primary key types followed by foreign
/// keys and M2M, and pgvector. Same setup as `integration.rs` (DATABASE_URL, `--features integration`).
use rango_orm_core::*;
use rango_orm_derive::Model;
use rango_orm_postgres::PgQueryExt;
use rango_orm_postgres::*;
use uuid::Uuid;

async fn pool() -> PgPool {
    let url = std::env::var("DATABASE_URL")
        .unwrap_or_else(|_| "postgres://postgres:postgres@localhost:5432/rango_test".to_string());
    PgPool::connect(&url)
        .await
        .expect("Failed to connect to test database")
}

// ── Foreign keys and M2M follow the target's primary key type ─────────────────

#[derive(Model, Debug, Clone)]
#[model(table = "rango_test_pk_author")]
struct PkAuthor {
    id: FieldAutoBigInt,
    name: FieldVarchar<1, 100>,
}

#[derive(Model, Debug, Clone)]
#[model(table = "rango_test_pk_label")]
struct PkLabel {
    id: FieldAutoInt,
    name: FieldVarchar<1, 100>,
}

#[derive(Model, Debug, Clone)]
#[model(table = "rango_test_pk_book")]
struct PkBook {
    id: FieldUuid,
    author_id: ForeignKey<PkAuthor>,
    editor_id: Option<ForeignKey<PkLabel>>,
    title: FieldVarchar<1, 100>,
    labels: ManyToMany<PkLabel>,
}

#[tokio::test]
#[cfg_attr(not(feature = "integration"), ignore)]
async fn test_fk_and_m2m_follow_the_target_pk_type() {
    let pool = pool().await;
    for ddl in [
        r#"DROP TABLE IF EXISTS "rango_test_pk_book_rango_test_pk_label""#,
        r#"DROP TABLE IF EXISTS "rango_test_pk_book""#,
        r#"DROP TABLE IF EXISTS "rango_test_pk_label""#,
        r#"DROP TABLE IF EXISTS "rango_test_pk_author""#,
        r#"CREATE TABLE "rango_test_pk_author" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" VARCHAR(100) NOT NULL)"#,
        r#"CREATE TABLE "rango_test_pk_label" ("id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" VARCHAR(100) NOT NULL)"#,
        r#"CREATE TABLE "rango_test_pk_book" ("id" UUID PRIMARY KEY, "author_id" BIGINT NOT NULL REFERENCES "rango_test_pk_author" ("id"), "editor_id" INTEGER REFERENCES "rango_test_pk_label" ("id"), "title" VARCHAR(100) NOT NULL)"#,
        r#"CREATE TABLE "rango_test_pk_book_rango_test_pk_label" ("rango_test_pk_book_id" UUID NOT NULL REFERENCES "rango_test_pk_book" ("id") ON DELETE CASCADE, "rango_test_pk_label_id" INTEGER NOT NULL REFERENCES "rango_test_pk_label" ("id") ON DELETE CASCADE, PRIMARY KEY ("rango_test_pk_book_id", "rango_test_pk_label_id"))"#,
    ] {
        sqlx::query(ddl).execute(&pool).await.unwrap();
    }

    // The schema derived from the models: FK columns take the target's key type.
    let col = |name: &str| {
        PkBook::schema()
            .columns
            .into_iter()
            .find(|c| c.name == name)
            .unwrap()
    };
    assert_eq!(col("author_id").col_type, ColumnType::BigInt);
    assert_eq!(col("editor_id").col_type, ColumnType::Int);
    assert_eq!(
        col("author_id").references.unwrap().table,
        "rango_test_pk_author"
    );

    let name = |s: &str| FieldVarchar::<1, 100>::new(s.to_string()).unwrap();
    let ann = insert(
        &pool,
        PkAuthor {
            id: FieldAutoBigInt(None),
            name: name("ann"),
        },
    )
    .await
    .unwrap();
    let bob = insert(
        &pool,
        PkAuthor {
            id: FieldAutoBigInt(None),
            name: name("bob"),
        },
    )
    .await
    .unwrap();
    let mut labels = Vec::new();
    for n in ["rust", "orm"] {
        let label = insert(
            &pool,
            PkLabel {
                id: FieldAutoInt(None),
                name: name(n),
            },
        )
        .await
        .unwrap();
        labels.push(label);
    }
    let (ann_id, bob_id) = (ann.id.0.unwrap(), bob.id.0.unwrap());
    let rust_id: i32 = labels[0].id.0.unwrap();

    // Insert and read back: bigint FK, nullable int FK (Some and None).
    let book = |title: &str, author: i64, editor: Option<i32>| PkBook {
        id: FieldUuid(Uuid::new_v4()),
        author_id: ForeignKey::new(author),
        editor_id: editor.map(ForeignKey::new),
        title: name(title),
        labels: ManyToMany::empty(),
    };
    let b1 = insert(&pool, book("one", ann_id, Some(rust_id)))
        .await
        .unwrap();
    let b2 = insert(&pool, book("two", ann_id, None)).await.unwrap();
    insert(&pool, book("three", bob_id, None)).await.unwrap();
    let got = get::<_, PkBook>(&pool, &b1.id.to_sql_value())
        .await
        .unwrap()
        .unwrap();
    assert_eq!(got.author_id.id(), ann_id);
    assert_eq!(got.editor_id.map(|e| e.id()), Some(rust_id));
    let got2 = get::<_, PkBook>(&pool, &b2.id.to_sql_value())
        .await
        .unwrap()
        .unwrap();
    assert!(got2.editor_id.is_none());

    // Filter by the raw key value.
    let anns = PkBook::filter(&pool)
        .eq(PkBook::AUTHOR_ID, ann_id)
        .all()
        .await
        .unwrap();
    assert_eq!(anns.len(), 2);

    // select_related: one JOIN, the author's bigint key decodes.
    let joined = PkBook::filter(&pool)
        .select_related(PkBook::AUTHOR_ID)
        .order_by("title")
        .all()
        .await
        .unwrap();
    assert_eq!(joined.len(), 3);
    // titles sorted: one, three, two
    assert_eq!(joined[0].related::<PkAuthor>().name.as_str(), "ann");
    assert_eq!(joined[1].related::<PkAuthor>().id.0, Some(bob_id));

    // prefetch_related over the reverse bigint FK.
    let authors = PkAuthor::filter(&pool)
        .prefetch_related(PkBook::AUTHOR_ID)
        .all()
        .await
        .unwrap();
    let books_of = |id: i64| {
        authors
            .iter()
            .find(|a| a.id.0 == Some(id))
            .unwrap()
            .prefetched::<PkBook>()
            .len()
    };
    assert_eq!((books_of(ann_id), books_of(bob_id)), (2, 1));

    // ManyToMany to an int key: add / all / reverse / exists / prefetch / remove.
    for l in &labels {
        M2M::<PkBook, PkLabel>::add(&pool, &b1, l).await.unwrap();
    }
    M2M::<PkBook, PkLabel>::add(&pool, &b2, &labels[0])
        .await
        .unwrap();
    assert_eq!(
        M2M::<PkBook, PkLabel>::all(&pool, &b1).await.unwrap().len(),
        2
    );
    assert_eq!(
        M2M::<PkBook, PkLabel>::reverse(&pool, &labels[0])
            .await
            .unwrap()
            .len(),
        2
    );
    assert!(
        M2M::<PkBook, PkLabel>::exists(&pool, &b2, &labels[0])
            .await
            .unwrap()
    );
    assert!(
        !M2M::<PkBook, PkLabel>::exists(&pool, &b2, &labels[1])
            .await
            .unwrap()
    );
    let with_labels = PkBook::filter(&pool)
        .prefetch_related(PkBook::LABELS)
        .all()
        .await
        .unwrap();
    let labels_of = |b: &PkBook| {
        with_labels
            .iter()
            .find(|w| w.id == b.id)
            .unwrap()
            .prefetched::<PkLabel>()
            .len()
    };
    assert_eq!((labels_of(&b1), labels_of(&b2)), (2, 1));
    M2M::<PkBook, PkLabel>::remove(&pool, &b1, &labels[1])
        .await
        .unwrap();
    assert_eq!(
        M2M::<PkBook, PkLabel>::all(&pool, &b1).await.unwrap().len(),
        1
    );
}

// ── pgvector ──────────────────────────────────────────────────────────────────

#[derive(Model, Debug, Clone, PartialEq)]
#[model(table = "rango_test_embedding")]
struct TestEmbedding {
    id: FieldUuid,
    label: FieldVarchar<1, 50>,
    embedding: FieldVector<3>,
    alt: Option<FieldVector<3>>,
}

fn emb(label: &str, v: [f32; 3], alt: Option<[f32; 3]>) -> TestEmbedding {
    TestEmbedding {
        id: FieldUuid(Uuid::new_v4()),
        label: FieldVarchar::new(label.to_string()).unwrap(),
        embedding: FieldVector::new(v.to_vec()).unwrap(),
        alt: alt.map(|a| FieldVector::new(a.to_vec()).unwrap()),
    }
}

async fn labels(q: QueryBuilder<'_, TestEmbedding>) -> Vec<String> {
    q.all()
        .await
        .unwrap()
        .into_iter()
        .map(|e| e.label.to_string())
        .collect()
}

#[tokio::test]
#[cfg_attr(not(feature = "integration"), ignore)]
async fn test_pg_vector_roundtrip_and_nearest() {
    let pool = pool().await;
    sqlx::query("CREATE EXTENSION IF NOT EXISTS vector")
        .execute(&pool)
        .await
        .unwrap();
    sqlx::query(r#"DROP TABLE IF EXISTS "rango_test_embedding""#)
        .execute(&pool)
        .await
        .unwrap();
    sqlx::query(r#"CREATE TABLE "rango_test_embedding" ("id" UUID PRIMARY KEY, "label" VARCHAR(50) NOT NULL, "embedding" vector(3) NOT NULL, "alt" vector(3))"#)
        .execute(&pool)
        .await
        .unwrap();

    let a = emb("a", [1.0, 0.0, 0.0], Some([0.5, 0.5, 0.0]));
    insert(&pool, a.clone()).await.unwrap();
    let n = bulk_create(
        &pool,
        &[
            emb("b", [0.9, 0.1, 0.0], None),
            emb("c", [0.0, 1.0, 0.0], None),
            emb("d", [0.0, 0.0, -1.0], Some([1.0, 1.0, 1.0])),
        ],
    )
    .await
    .unwrap();
    assert_eq!(n, 3);

    // Round trip, NULL included.
    let got = TestEmbedding::filter(&pool)
        .eq(TestEmbedding::LABEL, "a")
        .one()
        .await
        .unwrap()
        .unwrap();
    assert_eq!(got, a);
    let b = TestEmbedding::filter(&pool)
        .eq(TestEmbedding::LABEL, "b")
        .one()
        .await
        .unwrap()
        .unwrap();
    assert_eq!(b.alt, None);
    assert_eq!(b.embedding.as_slice(), &[0.9, 0.1, 0.0]);

    let q = FieldVector::<3>::new([1.0, 0.0, 0.0]).unwrap();
    let near = |d| TestEmbedding::filter(&pool).nearest(TestEmbedding::EMBEDDING, &q, 2, d);
    assert_eq!(labels(near(Distance::L2)).await, ["a", "b"]);
    assert_eq!(labels(near(Distance::Cosine)).await, ["a", "b"]);
    assert_eq!(labels(near(Distance::InnerProduct)).await, ["a", "b"]);

    // The distance ordering wins over a later order_by, which only breaks the
    // c/d tie (both at sqrt(2)); its placeholder follows the where binds.
    assert_eq!(
        labels(
            TestEmbedding::filter(&pool)
                .ne(TestEmbedding::LABEL, "a")
                .nearest(TestEmbedding::EMBEDDING, &q, 3, Distance::L2)
                .order_by(TestEmbedding::LABEL.desc())
        )
        .await,
        ["b", "d", "c"]
    );

    // L2 distance from q: a=0, b≈0.14, c≈1.41, d≈1.41.
    let mut close = labels(TestEmbedding::filter(&pool).within(
        TestEmbedding::EMBEDDING,
        &q,
        0.5,
        Distance::L2,
    ))
    .await;
    close.sort();
    assert_eq!(close, ["a", "b"]);

    // A nullable vector column works too; rows with NULL are ordered last.
    assert_eq!(
        labels(TestEmbedding::filter(&pool).nearest(
            TestEmbedding::ALT,
            &FieldVector::new([1.0, 1.0, 1.0]).unwrap(),
            1,
            Distance::L2
        ))
        .await,
        ["d"]
    );

    // The distance comes back with each row: the ORDER BY value, with its bind numbered
    // after the WHERE binds and before a later order_by.
    let with_distance: Vec<(String, f64)> = TestEmbedding::filter(&pool)
        .ne(TestEmbedding::LABEL, "a")
        .nearest(TestEmbedding::EMBEDDING, &q, 3, Distance::L2)
        .order_by(TestEmbedding::LABEL.desc())
        .all_with_distance()
        .await
        .unwrap()
        .into_iter()
        .map(|(e, d)| (e.label.to_string(), d))
        .collect();
    let expected = [
        ("b", 0.02f64.sqrt()),
        ("d", 2f64.sqrt()),
        ("c", 2f64.sqrt()),
    ];
    assert_eq!(with_distance.len(), 3);
    for ((label, d), (want_label, want_d)) in with_distance.iter().zip(expected) {
        assert_eq!(label, want_label);
        assert!((d - want_d).abs() < 1e-6, "{label}: {d} vs {want_d}");
    }

    // Column kind, dimension and finiteness are checked at compile time
    // (rango-orm/tests/ui/vector_*.rs); what is left fails before any SQL runs.
    fn err<T>(r: Result<T>) -> bool {
        matches!(r, Err(Error::Invalid(_)))
    }
    assert!(err(TestEmbedding::filter(&pool).all_with_distance().await));
    assert!(err(TestEmbedding::filter(&pool)
        .nearest(TestEmbedding::EMBEDDING, &q, 1, Distance::L2)
        .annotate_count("n")
        .aggregate()
        .await));
    // count ignores the ordering, so the distance bind must not leak into it.
    assert_eq!(
        TestEmbedding::filter(&pool)
            .ne(TestEmbedding::LABEL, "a")
            .nearest(TestEmbedding::EMBEDDING, &q, 2, Distance::L2)
            .count()
            .await
            .unwrap(),
        3
    );

    sqlx::query(r#"DROP TABLE "rango_test_embedding""#)
        .execute(&pool)
        .await
        .unwrap();
}

#[test]
fn test_field_vector_validates() {
    assert!(FieldVector::<3>::new(vec![1.0, 2.0, 3.0]).is_ok());
    assert!(FieldVector::<3>::new(vec![1.0, 2.0]).is_err());
    assert!(FieldVector::<3>::new(vec![1.0, f32::NAN, 3.0]).is_err());
    assert!(FieldVector::<3>::new(vec![1.0, f32::INFINITY, 3.0]).is_err());
    assert!(serde_json::from_str::<FieldVector<2>>("[1.0, 2.0, 3.0]").is_err());
}
